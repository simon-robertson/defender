// Static vector portraits derived from accepted model geometry; no asset edits.
import {meshPart} from '../shared/mesher.js';
import {partMatrices} from '../shared/math.js';
const portraits={};
const srgb=x=>Math.round(255*(x<=.0031308?12.92*x:1.055*x**(1/2.4)-.055));
const enemies=['dog','roller','moth','walker','dune-tread','twin-fan','tripod','ray','spider','lantern'];
for(const id of ['turret-study','arc-spire','missile-launcher','power-generator','drone-defence',...enemies]){
 const model=await Bun.file(new URL(`../assets/models/${id}.json`,import.meta.url)).json();
 for(const variant of (enemies.includes(id)||id==='power-generator'||id==='drone-defence'?['base']:['base','upgrade1','upgrade2'])){
  const parts=model.variants[variant].parts,matrices=partMatrices(parts),polygons=[],bounds=[Infinity,Infinity,-Infinity,-Infinity],eye=[.62,.65,-.8];
  for(const part of parts){const mesh=meshPart(model,part),m=matrices.get(part.id);
   for(let q=0;q<mesh.quads.length;q++){
    const k=q*44,v=mesh.vertices,n=[0,1,2].map(a=>m[a]*v[k+3]+m[4+a]*v[k+4]+m[8+a]*v[k+5]);
    if(n.reduce((s,x,i)=>s+x*eye[i],0)<=0)continue;
    const pts=[],depths=[];
    for(let j=0;j<4;j++){const i=k+j*11,p=[0,1,2].map(a=>m[a]*v[i]+m[4+a]*v[i+1]+m[8+a]*v[i+2]+m[12+a]);const x=(p[0]+p[2])*.8,y=(p[2]-p[0])*.38-p[1];pts.push([x,y]);depths.push(p.reduce((s,x,i)=>s+x*eye[i],0));bounds[0]=Math.min(bounds[0],x);bounds[1]=Math.min(bounds[1],y);bounds[2]=Math.max(bounds[2],x);bounds[3]=Math.max(bounds[3],y);}
    const light=.48+.52*Math.max(0,n[0]*.4+n[1]*.8-n[2]*.45),color=[6,7,8].map(i=>srgb(Math.min(1,v[k+i]*light))).map(x=>x.toString(16).padStart(2,'0')).join('');
    polygons.push({pts,depth:depths.reduce((a,b)=>a+b)/4,color});
   }
  }
  polygons.sort((a,b)=>a.depth-b.depth);const w=bounds[2]-bounds[0],h=bounds[3]-bounds[1],scale=Math.min(104/w,94/h),dx=(128-w*scale)/2-bounds[0]*scale,dy=(112-h*scale)/2-bounds[1]*scale;
  const body=polygons.map(p=>`<path d="M${p.pts.map(([x,y])=>(x*scale+dx).toFixed(2)+','+(y*scale+dy).toFixed(2)).join('L')}Z" fill="#${p.color}"/>`).join('');
  portraits[id+'-'+variant]='data:image/svg+xml,'+encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="128" height="112" viewBox="0 0 128 112">${body}</svg>`);
 }
}
await Bun.write(new URL('../play/portraits.js',import.meta.url),'// Generated by scripts/game-gui-icons.js from accepted model geometry.\nexport const PORTRAITS=Object.freeze('+JSON.stringify(portraits)+');\n');
console.log(`Generated ${Object.keys(portraits).length} model-derived vector portraits.`);
